"""
Reporting — render evaluation results as Markdown tables.

The Markdown output is what goes in the README and in a pull request, so
it needs to be readable without any tooling.
"""

from __future__ import annotations

from pathlib import Path

from eval.metrics import RunSummary, compare


def _pct(value: float) -> str:
    return f"{value * 100:.1f}%"


def summary_table(summary: RunSummary) -> str:
    """Render one run as a Markdown table."""
    lines = [
        f"### {summary.label}",
        "",
        "| Metric | Value |",
        "|---|---:|",
        f"| Tasks | {summary.total} |",
        f"| Success | {summary.success} |",
        f"| Success rate | {_pct(summary.success_rate)} |",
        f"| Mean steps | {summary.mean_steps:.2f} |",
        f"| Mean tool calls | {summary.mean_tool_calls:.2f} |",
        f"| Mean latency | {summary.mean_wall_ms:.0f} ms |",
        f"| Permission requests | {summary.permission_asks} |",
        f"| Permission denials | {summary.permission_denials} |",
        f"| Harness errors | {summary.errors} |",
        "",
    ]
    if summary.by_kind:
        lines += ["| Task kind | Success | Total | Rate |", "|---|---:|---:|---:|"]
        for kind, bucket in sorted(summary.by_kind.items()):
            lines.append(
                f"| {kind} | {bucket['success']} | {bucket['total']} "
                f"| {_pct(bucket['success_rate'])} |"
            )
        lines.append("")
    return "\n".join(lines)


def fault_matrix_table(summaries: list[RunSummary]) -> str:
    """Render one row per fault class."""
    lines = [
        "| Fault | Tasks | Success | Success rate | Mean steps |",
        "|---|---:|---:|---:|---:|",
    ]
    for s in summaries:
        name = s.fault or "none (baseline)"
        lines.append(
            f"| {name} | {s.total} | {s.success} | {_pct(s.success_rate)} "
            f"| {s.mean_steps:.2f} |"
        )
    lines.append("")
    return "\n".join(lines)


def comparison_table(baseline: RunSummary, candidate: RunSummary) -> str:
    """Render a before/after comparison."""
    delta = compare(baseline, candidate)
    sign = "+" if delta["delta_success_points"] >= 0 else ""
    lines = [
        "| Metric | Before | After | Delta |",
        "|---|---:|---:|---:|",
        f"| Success rate | {_pct(baseline.success_rate)} | "
        f"{_pct(candidate.success_rate)} | {sign}{delta['delta_success_points']} pts |",
        f"| Mean steps | {baseline.mean_steps:.2f} | {candidate.mean_steps:.2f} "
        f"| {delta['delta_mean_steps']:+.2f} |",
        f"| Mean latency | {baseline.mean_wall_ms:.0f} ms | "
        f"{candidate.mean_wall_ms:.0f} ms | {delta['delta_mean_wall_ms']:+.0f} ms |",
        "",
    ]
    return "\n".join(lines)


def render_report(
    baseline: RunSummary,
    fault_summaries: list[RunSummary] | None = None,
    candidate: RunSummary | None = None,
    oracle: bool = False,
) -> str:
    """Render the full evaluation report."""
    parts = [
        "# Agent Evaluation Report",
        "",
        "Generated by `python -m eval.cli --report`. All numbers come from "
        "programmatically verified tasks — no LLM judge is used for ground truth.",
        "",
    ]
    if oracle:
        parts += [
            "> **Reference-solver run.** These numbers were produced with the "
            "scripted oracle, not a live model. They are a structural "
            "regression baseline: the oracle always issues the same tool call, "
            "so a fault it cannot absorb shows as a task failure. Use a live "
            "model run to measure how much of each failure the *agent* "
            "recovers from.",
            "",
        ]
    parts += [summary_table(baseline)]
    if fault_summaries:
        parts += ["## Fault injection", "", fault_matrix_table(fault_summaries)]
    if candidate is not None:
        parts += ["## Before / after", "", comparison_table(baseline, candidate)]
    if baseline.failures:
        parts += ["## Baseline failures", ""]
        for failure in baseline.failures:
            parts.append(f"- `{failure['task_id']}` — {failure['detail']}")
        parts.append("")
    return "\n".join(parts)


def write_report(text: str, path: Path) -> None:
    """Write the report to disk."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
